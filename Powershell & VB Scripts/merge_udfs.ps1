# Merge xlwings UDF Python files
# Usage: .\merge_udfs.ps1

# Output file
$OutputFile = "consolidated_udfs.py"

# List of input files to merge
$Files = @(
    "ss.py",
    "udf.py",
    "udf2.py",
    "udf3.py",
    "udf4.py",
    "udf5.py",
    "udf6.py",
    "udf-dll.py",
    "java-test-udf.py",
    "udf7.py",
    "udf3-dll.py",
    "xl-to-js.py",
    "regex-msys-c.py",
    "regex-msys-c-multithreading.py",
    "regex-boost-msys.py",
    "intcalc.py",
    "xl_to_js2.py",
    "regex-msys-dll.py",
    "sqlite.py",
    "xlwings_sqlite_python.py",
    "xlwings_sqlite_python_pandas.py",
    "new-dll-14052025.py",
    "random-numbers-claude-24052025.py",
    "company_analytics.py",
    "BSE.py",
    "investingapicall.py"
)

# Collections for imports and functions
$AllImports = @()
$AllFunctions = @()

Write-Host "Starting merge process..." -ForegroundColor Green
Write-Host "==========================" -ForegroundColor Green
Write-Host ""

# Process each file
foreach ($file in $Files) {
    if (Test-Path $file) {
        Write-Host "Processing: $file" -ForegroundColor Cyan
        
        $content = Get-Content $file -Encoding UTF8
        $inImportSection = $true
        $functionLines = @()
        
        foreach ($line in $content) {
            # Check if line is an import
            if ($line -match '^\s*(import |from .* import )') {
                $AllImports += $line.Trim()
            }
            else {
                # Once we hit non-import, add to functions section
                if ($line.Trim().Length -gt 0 -or -not $inImportSection) {
                    $inImportSection = $false
                    $functionLines += $line
                }
            }
        }
        
        # Add separator and function content
        if ($functionLines.Count -gt 0) {
            $AllFunctions += ""
            $AllFunctions += "# ==================== FROM $file ===================="
            $AllFunctions += $functionLines
        }
    }
    else {
        Write-Host "Warning: $file not found, skipping..." -ForegroundColor Yellow
    }
}

Write-Host ""
Write-Host "Consolidating imports..." -ForegroundColor Cyan

# Remove duplicate imports and sort
$UniqueImports = $AllImports | Select-Object -Unique | Sort-Object

# Create output file
$OutputContent = @()
$OutputContent += '"""'
$OutputContent += "Consolidated xlwings UDF Module"
$OutputContent += "Auto-generated by merge script"
$OutputContent += '"""'
$OutputContent += ""
$OutputContent += $UniqueImports
$OutputContent += ""
$OutputContent += ""

Write-Host "Merging function definitions..." -ForegroundColor Cyan
$OutputContent += $AllFunctions

# Write to file
$OutputContent | Out-File -FilePath $OutputFile -Encoding UTF8

Write-Host ""
Write-Host "==========================" -ForegroundColor Green
Write-Host "Merge complete!" -ForegroundColor Green
Write-Host "Output file: $OutputFile" -ForegroundColor Green
Write-Host ""

# Statistics
$TotalLines = (Get-Content $OutputFile).Count
$ImportCount = ($UniqueImports | Measure-Object).Count
$FuncCount = (Select-String -Path $OutputFile -Pattern "@xw\.func" | Measure-Object).Count

Write-Host "Statistics:" -ForegroundColor Yellow
Write-Host "  - Import statements: $ImportCount"
Write-Host "  - UDF functions (@xw.func): $FuncCount"
Write-Host "  - Total lines: $TotalLines"
Write-Host ""
Write-Host "Please review $OutputFile for:" -ForegroundColor Yellow
Write-Host "  1. Duplicate function names" -ForegroundColor White
Write-Host "  2. Conflicting global variables" -ForegroundColor White
Write-Host "  3. Missing dependencies" -ForegroundColor White
